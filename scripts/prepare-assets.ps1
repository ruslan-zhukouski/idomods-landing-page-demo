param([switch]$InspectOnly)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$repoRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))

function Save-JpegDerivative([System.Drawing.Image]$Source, [string]$Target, [int]$Width) {
    if ($Width -gt $Source.Width) { return }
    $height = [int][Math]::Round($Source.Height * $Width / $Source.Width)
    $bitmap = [System.Drawing.Bitmap]::new($Width, $height)
    $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
    try {
        $graphics.Clear([System.Drawing.Color]::White)
        $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
        $graphics.DrawImage($Source, 0, 0, $Width, $height)
        $codec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object MimeType -eq 'image/jpeg'
        $parameters = [System.Drawing.Imaging.EncoderParameters]::new(1)
        try {
            $parameters.Param[0] = [System.Drawing.Imaging.EncoderParameter]::new([System.Drawing.Imaging.Encoder]::Quality, [long]86)
            $bitmap.Save($Target, $codec, $parameters)
        } finally { $parameters.Dispose() }
    } finally { $graphics.Dispose(); $bitmap.Dispose() }
}

if (-not $InspectOnly) {
    # Exact source-pixel crops from the Figma imageTransform values, not estimated cutouts.
    $lampSource = [System.Drawing.Bitmap]::FromFile((Join-Path $repoRoot 'docs/references/lamp-source.png'))
    try {
        if ($lampSource.Width -ne 1920 -or $lampSource.Height -ne 1080) { throw 'Unexpected lamp source size' }
        $crops = @(
            @{Name='lamp-beige'; X=760; Y=85; W=372; H=419},
            @{Name='lamp-terracotta'; X=418; Y=434; W=423; H=393}
        )
        foreach ($crop in $crops) {
            $rectangle = [System.Drawing.Rectangle]::new($crop.X, $crop.Y, $crop.W, $crop.H)
            $bitmap = $lampSource.Clone($rectangle, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
            try { $bitmap.Save((Join-Path $repoRoot ('assets/images/' + $crop.Name + '.png')), [System.Drawing.Imaging.ImageFormat]::Png) }
            finally { $bitmap.Dispose() }
        }
    } finally { $lampSource.Dispose() }
    # Green is the original vector-masked export: a rectangle would include a neighboring lamp.
    if (-not (Test-Path -LiteralPath (Join-Path $repoRoot 'assets/images/lamp-green.png'))) { throw 'Missing vector-masked green lamp export' }

    foreach ($photo in @('hero-bestsellers','hero-interior','thoro')) {
        $source = [System.Drawing.Image]::FromFile((Join-Path $repoRoot "assets/images/$photo.png"))
        try {
            foreach ($width in @(480,640,960,1280,1600,1920)) {
                Save-JpegDerivative $source (Join-Path $repoRoot "assets/images/$photo-$width.jpg") $width
            }
        } finally { $source.Dispose() }
    }
}

$inspection = foreach ($file in Get-ChildItem -LiteralPath (Join-Path $repoRoot 'assets') -File -Recurse | Sort-Object FullName) {
    $relative = [System.IO.Path]::GetRelativePath($repoRoot, $file.FullName).Replace('\','/')
    $row = [ordered]@{path=$relative; bytes=$file.Length; sha256=(Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant()}
    if ($file.Extension -in @('.png','.jpg')) {
        $image = [System.Drawing.Bitmap]::FromFile($file.FullName)
        try {
            $row.width = $image.Width; $row.height = $image.Height; $row.pixelFormat = [string]$image.PixelFormat
            if ($file.BaseName -match '^lamp-(beige|green|terracotta)$') {
                $transparent = 0; $partial = 0; $opaque = 0
                for ($y=0; $y -lt $image.Height; $y++) {
                    for ($x=0; $x -lt $image.Width; $x++) {
                        $alpha = $image.GetPixel($x,$y).A
                        if ($alpha -eq 0) { $transparent++ } elseif ($alpha -eq 255) { $opaque++ } else { $partial++ }
                    }
                }
                $row.alpha = @{transparentPixels=$transparent; antialiasedPixels=$partial; opaquePixels=$opaque; cornerAlpha=@($image.GetPixel(0,0).A,$image.GetPixel($image.Width-1,0).A,$image.GetPixel(0,$image.Height-1).A,$image.GetPixel($image.Width-1,$image.Height-1).A)}
                if ($transparent -eq 0 -or $opaque -eq 0) { throw "Invalid lamp alpha: $relative" }
            }
        } finally { $image.Dispose() }
    } elseif ($file.Extension -eq '.webp') {
        # Generated by encode-webp.html at exactly the corresponding JPEG dimensions.
        $fallback = [System.Drawing.Image]::FromFile([System.IO.Path]::ChangeExtension($file.FullName, '.jpg'))
        try { $row.width = $fallback.Width; $row.height = $fallback.Height } finally { $fallback.Dispose() }
    } elseif ($file.Extension -eq '.svg') {
        $svg = [xml](Get-Content -Raw -LiteralPath $file.FullName)
        $row.width = [string]$svg.DocumentElement.width; $row.height = [string]$svg.DocumentElement.height
        $row.viewBox = [string]$svg.DocumentElement.viewBox
    }
    [pscustomobject]$row
}
$inspection | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $repoRoot 'docs/asset-inspection.json') -Encoding utf8
$inspection | Where-Object { $_.path -match 'lamp-|hero-|thoro' } | Select-Object path,width,height,bytes,alpha | ConvertTo-Json -Depth 5
